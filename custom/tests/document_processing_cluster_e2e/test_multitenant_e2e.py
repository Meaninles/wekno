class TenantProvisionerCleanupTests(unittest.TestCase):
    def test_generated_local_account_username_contains_no_run_id_punctuation(self) -> None:
        class Admin(_ProvisionAdmin):
            def request(self, method: str, path: str, **kwargs: object) -> object:
                if method == "POST" and path == "/api/v1/custom/admin/users":
                    body = kwargs.get("json_body")
                    assert isinstance(body, dict)
                    self.username = str(body["username"])
                return super().request(method, path, **kwargs)

        with tempfile.TemporaryDirectory() as raw:
            admin = Admin()
            provisioner = TenantProvisioner(
                admin,  # type: ignore[arg-type]
                JsonlRecorder(Path(raw) / "events.jsonl"),
            )
            provisioner._create_account(3, "dual-real-20260724-233733-a1b2c3")

            self.assertRegex(admin.username, r"^[A-Za-z0-9]{2,20}$")
            self.assertNotIn("-", admin.username)

    def test_partial_account_is_cleaned_when_model_grant_fails(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            admin = _ProvisionAdmin()
            provisioner = _GrantFailureProvisioner(
                admin,  # type: ignore[arg-type]
                JsonlRecorder(Path(raw) / "events.jsonl"),
            )

            with self.assertRaisesRegex(E2EFailure, "grant failed"):
                provisioner.provision(
                    principal_count=1,
                    knowledge_bases_per_principal=2,
                    run_suffix="unit-test",
                )

            self.assertIn(("DELETE", "/api/v1/tenants/12345"), admin.calls)
            self.assertIn(
                ("PUT", "/api/v1/custom/admin/users/user-1/active"),
                admin.calls,
            )

    def test_required_qwen_models_never_fall_back(self) -> None:
        models = [
            {"id": "omni", "name": "/models/Qwen2.5-Omni-7B", "type": "VLLM"},
            {"id": "sense", "name": "FunAudioLLM/SenseVoiceSmall", "type": "ASR"},
        ]
        with self.assertRaisesRegex(E2EFailure, "Qwen3-VL-32B-Instruct"):
            TenantProvisioner._require_exact_model(
                models, "vllm", EXACT_QWEN_VLM_NAME
            )
        with self.assertRaisesRegex(E2EFailure, "Qwen3-ASR-1.7B"):
            TenantProvisioner._require_exact_model(
                models, "asr", EXACT_QWEN_ASR_NAME
            )

    def test_real_non_audio_corpus_keeps_exact_asr_binding_but_disables_calls(self) -> None:
        models = type(
            "Models",
            (),
            {
                "chat_id": "chat",
                "embedding_id": "embedding",
                "vlm_id": "vlm",
                "asr_id": "qwen-asr",
            },
        )()
        body = TenantProvisioner._kb_body(
            "公司制度",
            models,  # type: ignore[arg-type]
            asr_enabled=False,
            wiki_ingest_batch_size=20,
            wiki_ingest_map_parallel=4,
            wiki_ingest_reduce_parallel=4,
        )

        self.assertEqual(body["asr_config"]["model_id"], "qwen-asr")
        self.assertFalse(body["asr_config"]["enabled"])
        self.assertEqual(body["wiki_config"]["ingest_batch_size"], 20)
        self.assertEqual(body["wiki_config"]["ingest_map_parallel"], 4)
        self.assertEqual(body["wiki_config"]["ingest_reduce_parallel"], 4)

    def test_provision_accepts_real_corpus_kb_name_and_tuning(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            admin = _ProvisionAdmin()
            provisioner = _ProvisionWithoutRemoteModels(
                admin,  # type: ignore[arg-type]
                JsonlRecorder(Path(raw) / "events.jsonl"),
            )
            created: dict[str, object] = {}

            def client_request(
                _client: object,
                method: str,
                path: str,
                **kwargs: object,
            ) -> object:
                self.assertEqual((method, path), ("POST", "/api/v1/knowledge-bases"))
                body = kwargs.get("json_body")
                self.assertIsInstance(body, dict)
                created.update(body)  # type: ignore[arg-type]
                return {"id": "kb-1", "summary_model_id": "chat"}

            with patch.object(APIClient, "request", new=client_request):
                principals = provisioner.provision(
                    principal_count=1,
                    knowledge_bases_per_principal=1,
                    run_suffix="real-corpus",
                    knowledge_base_name_factory=lambda _principal, _kb: "数据资料",
                    knowledge_base_body_kwargs={
                        "asr_enabled": False,
                        "wiki_ingest_batch_size": 20,
                    },
                )

            self.assertEqual(principals[0].knowledge_base_ids, ["kb-1"])
            self.assertEqual(created["name"], "数据资料")
            self.assertFalse(created["asr_config"]["enabled"])  # type: ignore[index]
            self.assertEqual(created["wiki_config"]["ingest_batch_size"], 20)  # type: ignore[index]


