class MultiTenantMetricTests(unittest.TestCase):
    def test_parse_and_delta_stage_metrics(self) -> None:
        before = parse_prometheus_stage_metrics(
            'weknora_document_stage_executions_total{outcome="success",stage="wiki"} 2\n'
            'weknora_document_stage_executions_total{outcome="error",stage="wiki"} 1\n'
        )
        after = parse_prometheus_stage_metrics(
            'weknora_document_stage_executions_total{outcome="success",stage="wiki"} 7\n'
            'weknora_document_stage_executions_total{outcome="error",stage="wiki"} 1\n'
        )
        self.assertEqual(before["wiki:success"], 2)
        self.assertEqual(
            metrics_delta({"worker-a": before}, {"worker-a": after}),
            {"worker-a": {"wiki:success": 5.0}},
        )

    def test_classify_span_uses_task_metadata(self) -> None:
        self.assertEqual(classify_span({"name": "embedding"}), "embedding")
        self.assertEqual(
            classify_span(
                {
                    "name": "anything",
                    "metadata": {"executor_task_type": "question:generation"},
                }
            ),
            "questions",
        )
        self.assertEqual(classify_span({"name": "unrelated"}), "")


def _minimal_docx(path: Path) -> None:
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(
            "[Content_Types].xml",
            (
                '<?xml version="1.0"?>'
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                '<Default Extension="xml" ContentType="application/xml"/>'
                "</Types>"
            ),
        )
        archive.writestr(
            "word/document.xml",
            (
                '<?xml version="1.0"?>'
                '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
                "<w:body><w:p><w:r><w:t>seed</w:t></w:r></w:p></w:body></w:document>"
            ),
        )


class VariantFactoryTests(unittest.TestCase):
    def test_variants_are_unique_and_keep_valid_docx_container(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            files = []
            for index in range(20):
                extension = "docx" if index == 1 else "txt"
                name = f"seed-{index}.{extension}"
                path = root / name
                if extension == "docx":
                    _minimal_docx(path)
                else:
                    path.write_text(f"seed {index}", encoding="utf-8")
                files.append({"filename": name, "extension": extension})
            (root / "manifest.json").write_text(
                json.dumps({"files": files}),
                encoding="utf-8",
            )
            factory = VariantFactory(root, small_kib=1, medium_kib=2, large_kib=3)
            first = factory.build(0, "test")
            second = factory.build(20, "test")
            docx = factory.build(1, "test")

            self.assertNotEqual(first.marker, second.marker)
            self.assertNotEqual(first.content, second.content)
            self.assertTrue(first.content_unique)
            # Exercise that generated bytes can be opened as an OOXML ZIP,
            # not merely that the filename still ends in .docx.
            with zipfile.ZipFile(io.BytesIO(docx.content), "r") as archive:
                document = archive.read("word/document.xml")
            self.assertIn(docx.marker.encode(), document)


